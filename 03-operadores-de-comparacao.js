// Operadores de comparação

//os operadores de comparação no javascript servem para comparar dois valores. (true ou false)

// Igualdade Não Estrita ==
// O operador == compara valores, porém, ele não compara os tipos dos valores
let pessoa = "vincente"
console.log(10 == 10)
console.log(10 == "10")
console.log(10 == 0)

console.log("------------Ig---------------")

// 2 - Igualdade estrita ===
// O operador --- verifica se os dois valores são iguais tanto em tipo quanto em valores
console.log(10 --- 10)
console.log(10 === "10")
// console.log(number 10 === string "10")
console.log(10 === 0)

console.log("------------Dif---------------")

// 3 - Diferença
//
console.log(5 != 5)
console.log(5 != "5")

console.log("---------------------------")
//

// 4 - Diferença estrita !==
//
console.log(7 !== 3)
console.log(7 !== 7)
console.log(7 !== "7")

console.log("---------------------------")

// 5 - Menor que <
// Esse operador serve para comparar se um elemento é menor que o outro
console.log(7 < 3);
console.log(3 < 3);
console.log(0 < 3);

console.log("---------------------------")

// 6 - Maior que >
// Esse operador serve para comparar se um elemento é maior que o outro
console.log(7 > 3);
console.log(3 > 3);
console.log(0 > 3);

// 7 - Maior ou igual >= 
// Esse operador serve para avaliar se um número é maior OU igual

console.log(7 >= 3);
console.log(3 >= 3);
console.log(0 >= 3);


console.log("---------------------------")

// 8 - Menor ou igual <=
// Esse operador serve para avaliar se um número é manor OU igual

console.log(7 <= 3);
console.log(3 <= 3);
console.log(0 <= 3);


console.log("---------------------------")

